import { describe, it, expect, vi, beforeEach, beforeAll } from 'vitest';
import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import PersonasPermisos from './PersonasPermisos';
import { api } from '../utils/api';
import modulos from '../utils/modulosAcceso.json';
vi.mock('../utils/api',()=>({api:{get:vi.fn(),post:vi.fn(),patch:vi.fn()}}));
beforeAll(()=>{
 HTMLDialogElement.prototype.showModal = function(){ this.setAttribute('open',''); };
 HTMLDialogElement.prototype.close = function(){ this.removeAttribute('open'); };
});
const datos={tienda:{id:7,nombre:'Tienda Norte'},modulos:[{clave:'comercial',nombre:'Gestión Comercial',gestionable:true},{clave:'logistica',nombre:'Gestión Logística',gestionable:true}],personas:[]};
beforeEach(()=>{vi.clearAllMocks();api.get.mockResolvedValue(datos);});
it('abre una ventana y busca sin perder los permisos de secciones ocultas',async()=>{
 api.get.mockResolvedValue({...datos,modulos});
 render(<PersonasPermisos/>);
 fireEvent.click(await screen.findByRole('button',{name:'Agregar persona'}));
 expect(screen.getByRole('dialog',{name:'Agregar persona'})).toHaveAttribute('open');
 fireEvent.change(screen.getByLabelText('Buscar secciones'),{target:{value:'depositos'}});
 expect(screen.getAllByRole('combobox')).toHaveLength(1);
 fireEvent.change(screen.getByLabelText('Acceso a Depósitos'),{target:{value:'gestionar'}});
 fireEvent.change(screen.getByLabelText('Buscar secciones'),{target:{value:'no existe'}});
 expect(screen.getByText(/No hay secciones/)).toBeTruthy();
 fireEvent.click(screen.getByRole('button',{name:'Limpiar búsqueda'}));
 expect(screen.getByLabelText('Acceso a Depósitos')).toHaveValue('gestionar');
 expect(screen.getByLabelText('Acceso a Gestión Comercial')).toHaveValue('ver');
 fireEvent.click(screen.getByRole('button',{name:'Cerrar ventana'}));
 expect(screen.getByText(/Tenés cambios sin guardar/)).toBeTruthy();
 fireEvent.click(screen.getByRole('button',{name:'Seguir editando'}));
 expect(screen.getByLabelText('Acceso a Depósitos')).toHaveValue('gestionar');
 fireEvent.click(screen.getByRole('button',{name:'Cancelar'}));
 fireEvent.click(screen.getByRole('button',{name:'Descartar cambios'}));
 expect(screen.queryByRole('dialog')).toBeNull();
});
it('permite asignar cualquier sección del catálogo y conserva combinaciones al editar',async()=>{
 api.get.mockResolvedValue({...datos,modulos,personas:[{id:3,nombre:'Ana',email:'ana@example.com',estado:'activo',permisos:{productos:'ver'}}]});
 render(<PersonasPermisos/>);
 fireEvent.click(await screen.findByRole('button',{name:'Editar permisos'}));
 expect(screen.getAllByRole('combobox')).toHaveLength(16);
 fireEvent.change(screen.getByLabelText('Acceso a Mi E-commerce'),{target:{value:'gestionar'}});
 fireEvent.change(screen.getByLabelText('Acceso a Control Financiero'),{target:{value:'ver'}});
 fireEvent.click(screen.getByRole('button',{name:'Guardar permisos'}));
 await waitFor(()=>expect(api.patch).toHaveBeenCalledWith('/api/personas/3',{permisos:{productos:'ver',ecommerce:'gestionar',finanzas:'ver'}}));
});
it('crea la cuenta con contraseña definida por el propietario y acceso exclusivamente comercial',async()=>{
 api.post.mockResolvedValue({id:3});
 render(<PersonasPermisos/>);
 fireEvent.click(await screen.findByRole('button',{name:'Agregar persona'}));
 fireEvent.change(screen.getByLabelText('Nombre'),{target:{value:'Ana'}});
 fireEvent.change(screen.getByLabelText('Correo electrónico'),{target:{value:'ana@example.com'}});
 fireEvent.change(screen.getByLabelText('Contraseña inicial'),{target:{value:'ClaveSegura123'}});
 fireEvent.change(screen.getByLabelText('Confirmar contraseña'),{target:{value:'ClaveSegura123'}});
 fireEvent.change(screen.getByLabelText('Acceso a Gestión Comercial'),{target:{value:'gestionar'}});
 fireEvent.click(screen.getByRole('button',{name:'Crear persona'}));
 await waitFor(()=>expect(api.post).toHaveBeenCalledWith('/api/personas',{nombre:'Ana',email:'ana@example.com',password:'ClaveSegura123',permisos:{comercial:'gestionar'}}));
 expect(await screen.findByText(/Cuenta creada. Ya puede ingresar/)).toBeTruthy();
 expect(screen.queryByLabelText('Contraseña inicial')).toBeNull();
});
it('no crea la cuenta si las contraseñas no coinciden',async()=>{
 render(<PersonasPermisos/>);
 fireEvent.click(await screen.findByRole('button',{name:'Agregar persona'}));
 fireEvent.change(screen.getByLabelText('Nombre'),{target:{value:'Ana'}});
 fireEvent.change(screen.getByLabelText('Correo electrónico'),{target:{value:'ana@example.com'}});
 fireEvent.change(screen.getByLabelText('Contraseña inicial'),{target:{value:'ClaveSegura123'}});
 fireEvent.change(screen.getByLabelText('Confirmar contraseña'),{target:{value:'OtraClave123'}});
 fireEvent.click(screen.getByRole('button',{name:'Crear persona'}));
 expect(await screen.findByRole('alert')).toHaveTextContent('Las contraseñas no coinciden.');
 expect(api.post).not.toHaveBeenCalled();
});
it('edita permisos sin cambiar identidad y confirma antes de revocar',async()=>{
 api.get.mockResolvedValue({...datos,personas:[{id:3,nombre:'Ana',email:'ana@example.com',estado:'activo',permisos:{comercial:'gestionar'}}]});
 api.patch.mockResolvedValue({}); render(<PersonasPermisos/>);
 fireEvent.click(await screen.findByRole('button',{name:'Editar permisos'}));
 expect(screen.getByLabelText('Correo electrónico')).toBeDisabled();
 fireEvent.change(screen.getByLabelText('Acceso a Gestión Comercial'),{target:{value:'ver'}});
 fireEvent.click(screen.getByRole('button',{name:'Guardar permisos'}));
 await waitFor(()=>expect(api.patch).toHaveBeenCalledWith('/api/personas/3',{permisos:{comercial:'ver'}}));
 await waitFor(()=>expect(screen.queryByRole('button',{name:'Guardar permisos'})).toBeNull());
 fireEvent.click(screen.getByRole('button',{name:'Revocar acceso'}));
 expect(api.patch).toHaveBeenCalledTimes(1);
 fireEvent.click(screen.getAllByRole('button',{name:'Revocar acceso'})[1]);
 await waitFor(()=>expect(api.patch).toHaveBeenCalledWith('/api/personas/3',{estado:'revocado'}));
});
